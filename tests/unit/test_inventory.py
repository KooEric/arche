import hashlib
import os

import pytest

from arche_lib import inventory


def _entry(result, path):
    return next(entry for entry in result["files"] if entry["path"] == path)


@pytest.mark.parametrize(
    "text, expected",
    [("", 0), ("a", 1), ("a\n", 1), ("a\nb", 2), ("a\nb\n", 2), ("\n", 1)],
)
def test_count_lines(text, expected):
    assert inventory.count_lines(text) == expected


def test_supported_source_file_is_analyzed_with_size_lines_and_hash(make_repo):
    source = "x = 1\ny = 2\n"
    repo = make_repo({"src/app.py": source}, use_git=False)

    entry = inventory.classify(repo, "src/app.py")

    assert entry == {
        "path": "src/app.py",
        "status": "analyzed",
        "lang": "python",
        "bytes": len(source),
        "lines": 2,
        "sha256": hashlib.sha256(source.encode()).hexdigest(),
    }


@pytest.mark.parametrize(
    "path",
    [".env", ".env.local", "deploy/server.pem", "id_rsa", "config/credentials.prod.json",
     "android/app/google-services.json"],
)
def test_secret_files_are_skipped_without_being_read(make_repo, path):
    repo = make_repo({path: "TOKEN=value\n"}, use_git=False)

    assert inventory.classify(repo, path) == {"path": path, "status": "skipped", "reason": "secret"}


@pytest.mark.parametrize(
    "path, content, reason",
    [
        ("lib/vendor/x.py", "x = 1\n", "vendored"),
        ("node_modules/pkg/index.py", "x = 1\n", "vendored"),
        ("lib/api.g.dart", "class A {}\n", "generated"),
        ("poetry.lock", "# lock\n", "generated"),
        ("gen/schema.py", "# Generated by protoc.  DO NOT EDIT!\nx = 1\n", "generated"),
        ("README.md", "# readme\n", "unsupported_lang"),
    ],
)
def test_text_files_are_skipped_with_a_reason_but_still_hashed(make_repo, path, content, reason):
    repo = make_repo({path: content}, use_git=False)

    entry = inventory.classify(repo, path)

    assert (entry["status"], entry["reason"]) == ("skipped", reason)
    assert entry["sha256"] == hashlib.sha256(content.encode()).hexdigest()
    assert entry["lines"] == inventory.count_lines(content)


def test_generated_marker_after_the_header_lines_is_ignored(make_repo):
    body = "x = 1\n" * inventory.GENERATED_HEADER_LINES + "# DO NOT EDIT\n"
    repo = make_repo({"late.py": body}, use_git=False)

    assert inventory.classify(repo, "late.py")["status"] == "analyzed"


def test_binary_and_oversized_files_are_skipped_without_a_hash(make_repo):
    repo = make_repo(
        {"logo.bin": b"\x89PNG\x00\x01", "big.py": "#" * (inventory.MAX_BYTES + 1)},
        use_git=False,
    )

    assert inventory.classify(repo, "logo.bin") == {
        "path": "logo.bin", "status": "skipped", "reason": "binary", "bytes": 6,
    }
    assert inventory.classify(repo, "big.py") == {
        "path": "big.py", "status": "skipped", "reason": "too_large", "bytes": inventory.MAX_BYTES + 1,
    }


def test_symlinks_are_skipped_and_never_followed(make_repo, tmp_path):
    outside = tmp_path / "outside.py"
    outside.write_text("secret = 1\n", encoding="utf-8")
    repo = make_repo({"a.py": "x = 1\n"}, use_git=False)
    os.symlink(outside, repo / "link.py")

    assert inventory.classify(repo, "link.py") == {
        "path": "link.py", "status": "skipped", "reason": "symlink",
    }


def test_walk_prunes_git_and_reports_vendored_and_linked_dirs_once(make_repo, tmp_path):
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    repo = make_repo(
        {"a.py": "x = 1\n", "pkg/b.py": "y = 2\n", "node_modules/m/i.js": "1\n", ".git/config": "[core]\n"},
        use_git=False,
    )
    os.symlink(elsewhere, repo / "linked")

    assert inventory.walk_files(repo) == ["a.py", "linked", "node_modules", "pkg/b.py"]


def test_inventory_without_git_has_no_commit(make_repo):
    repo = make_repo({"a.py": "x = 1\n", "node_modules/m/i.js": "1\n"}, use_git=False)

    result = inventory.build_inventory(repo)

    assert result["repo"] == {"name": "repo", "root": str(repo), "commit": None, "dirty": None}
    assert _entry(result, "node_modules") == {
        "path": "node_modules", "status": "skipped", "reason": "vendored",
    }
    assert [entry["path"] for entry in result["files"]] == ["a.py", "node_modules"]


def test_inventory_with_git_honours_gitignore_and_drops_deleted_files(make_repo):
    repo = make_repo({".gitignore": "ignored.py\n", "a.py": "x = 1\n", "gone.py": "z = 0\n"})
    (repo / "ignored.py").write_text("skip = 1\n", encoding="utf-8")
    (repo / "new.py").write_text("y = 2\n", encoding="utf-8")
    (repo / "gone.py").unlink()

    result = inventory.build_inventory(repo)

    assert [entry["path"] for entry in result["files"]] == [".gitignore", "a.py", "new.py"]
    assert len(result["repo"]["commit"]) == 40
    assert result["repo"]["dirty"] is True


def test_tracked_file_inside_a_vendored_dir_is_listed_individually(make_repo):
    repo = make_repo({"vendor/lib/util.py": "x = 1\n"})

    result = inventory.build_inventory(repo)

    assert _entry(result, "vendor/lib/util.py")["reason"] == "vendored"
